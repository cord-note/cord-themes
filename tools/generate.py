"""Builds theme.css and theme.json for the curated palette themes in tools/palettes.py.

Each palette gives a few role colours per scheme (background, text, accent, link). Everything
else Cord needs (surfaces, borders, muted text, hover and danger colours) is derived here, and
any colour that misses its contrast target is nudged in lightness, keeping its hue.

Usage:  python tools/generate.py            # writes themes/<id>/ for every generated theme
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from colour import CONTRAST, contrast, fit, is_dark, mix, rgba, shift  # noqa: E402
from palettes import PALETTES  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..')
DANGER = {'dark': '#f0646e', 'light': '#c22f3a'}


def derive(s, dark):
    bg, text = s['bg'], s['text']
    surf = lambda t: mix(bg, text, t)  # noqa: E731
    p = {'bg': bg}
    if dark:
        p['bg-sidebar'] = mix(bg, '#000000', 0.28)
        p['bg-panel'] = mix(bg, '#000000', 0.14)
        p['bg-input'] = surf(0.05)
        p['bg-elevated'] = surf(0.10)
    else:
        p['bg-sidebar'] = surf(0.07)
        p['bg-panel'] = surf(0.04)
        p['bg-input'] = mix(bg, '#ffffff', 0.35)
        p['bg-elevated'] = mix(bg, '#ffffff', 0.55)
    p['bg-hover'] = surf(0.08 if dark else 0.07)
    p['border'] = surf(0.13 if dark else 0.12)
    p['border-strong'] = surf(0.26 if dark else 0.25)
    p['border-muted'] = surf(0.08 if dark else 0.07)

    p['text-primary'] = fit(text, bg, 7.0)
    p['text-secondary'] = fit(mix(p['text-primary'], bg, 0.22), bg, CONTRAST['text-secondary'])
    p['text-muted'] = fit(mix(p['text-primary'], bg, 0.42), bg, CONTRAST['text-muted'])
    # Muted text also sits on the darker/lighter panels; keep it readable there too.
    for surface in (p['bg-panel'], p['bg-sidebar']):
        p['text-muted'] = fit(p['text-muted'], surface, 3.0)

    accent = fit(s['accent'], bg, CONTRAST['accent'])
    p['accent'] = accent
    p['accent-hover'] = shift(accent, 0.06 if dark else -0.07)
    candidates = [bg, p['text-primary'], '#ffffff', '#0d0d0d']
    p['accent-fg'] = max(candidates, key=lambda c: contrast(c, accent))

    # Selected rows are tinted with the accent, but body text on them must stay readable.
    ratio = 0.24 if dark else 0.2
    active = mix(bg, accent, ratio)
    while contrast(p['text-primary'], active) < 4.5 and ratio > 0.04:
        ratio -= 0.02
        active = mix(bg, accent, ratio)
    p['bg-active'] = active

    p['link-color'] = fit(s.get('link', accent), bg, CONTRAST['link-color'])
    p['link-underline'] = rgba(p['link-color'], 0.3)
    danger = fit(s.get('danger', DANGER['dark' if dark else 'light']), bg, 4.5)
    p['danger'] = danger
    p['danger-hover-bg'] = rgba(danger, 0.12 if dark else 0.10)
    p['danger-border'] = rgba(danger, 0.3)
    p['close-hover-bg'] = danger
    p['close-hover-fg'] = '#ffffff' if contrast(danger, '#ffffff') >= contrast(danger, '#0d0d0d') else '#0d0d0d'
    return p


def block(selector, p):
    groups = [
        ['accent', 'accent-hover', 'accent-fg'],
        ['bg', 'bg-sidebar', 'bg-panel', 'bg-hover', 'bg-active', 'bg-input', 'bg-elevated'],
        ['border', 'border-strong', 'border-muted'],
        ['text-primary', 'text-secondary', 'text-muted'],
        ['link-color', 'link-underline', 'danger', 'danger-hover-bg', 'danger-border', 'close-hover-bg', 'close-hover-fg'],
    ]
    lines = []
    for g in groups:
        width = max(len(t) for t in g) + 3
        lines += [f'  --{t}:'.ljust(width + 2) + f' {p[t]};' for t in g]
        lines.append('')
    return f'{selector} {{\n' + '\n'.join(lines).rstrip() + '\n}\n'


def build(pal):
    tid = pal['id']
    dark, light = derive(pal['dark'], True), derive(pal['light'], False)
    if not is_dark(dark['bg']) or is_dark(light['bg']):
        raise SystemExit(f'{tid}: the dark background must be dark and the light one light')
    credit = pal['palette']['credit']
    dark_sel = '[data-theme="%s"]' % tid
    light_sel = '[data-theme="%s"][data-scheme="light"]' % tid
    css = (f'/* {pal["name"]} for Cord. Palette: {credit}. Generated by tools/generate.py; '
           f'edit tools/palettes.py, not this file. */\n\n'
           f'/* ── Dark ── */\n{block(dark_sel, dark)}\n'
           f'/* ── Light ── */\n{block(light_sel, light)}')
    meta = {
        'name': pal['name'],
        'description': pal['description'],
        'author': f'Palette: {credit}',
        'group': pal['group'],
        'tags': pal['tags'],
        'palette': pal['palette'],
    }
    d = os.path.join(ROOT, 'themes', tid)
    os.makedirs(d, exist_ok=True)
    # Lock-screen scenes are written by hand, so keep them across regeneration.
    old = os.path.join(d, 'theme.json')
    if os.path.isfile(old):
        scenes = json.load(open(old, encoding='utf-8')).get('scenes')
        if scenes:
            meta['scenes'] = scenes
    with open(os.path.join(d, 'theme.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)
    with open(os.path.join(d, 'theme.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)
        f.write('\n')


if __name__ == '__main__':
    for pal in PALETTES:
        build(pal)
    print(f'generated {len(PALETTES)} themes')
